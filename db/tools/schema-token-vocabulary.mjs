// A pure-digit token is not shorthand for anything -- it is a magnitude or an
// ordinal that the surrounding words already qualify (`field_goals_made_0_19_yards`,
// `solo_tackle_1_gsis`). Recognised by shape so no digit needs listing.
const is_numeric_token = (token) => /^\d+$/.test(token)

export const schema_token_vocabulary = new Set([
  ...english_words,
  ...domain_words,
  ...ratified_system_names,
  ...ratified_identifier_tokens,
  ...ratified_metric_names
])

export function is_vocabulary_token(token) {
  return is_numeric_token(token) || schema_token_vocabulary.has(token)
}

// Every token of `name` that the vocabulary does not recognise, in order.
export function nonconforming_tokens(name) {
  return name.split('_').filter((token) => token && !is_vocabulary_token(token))
}

