// The project's positive token vocabulary -- the oracle for the shorthand rule
// in audit-schema-conformance.mjs.
//
// The rule that rides on this file is: every token of a column name must be a
// member. That is the only shape that can see shorthand sitting in an INTERIOR
// token, which is the false-conformance class this vocabulary was built to
// close -- `player_fuml_gsis`, `yds_gained` and `deep_pass_att_percentage` all
// read CLEAN under a rule that tests the bare name alone.
//
// Why a positive vocabulary and not a dictionary. A dictionary-membership
// oracle was measured against this schema and is unusable: it flags 1,679 of
// 4,636 columns across 149 of 176 tables, and -- far worse -- it structurally
// CANNOT flag `prob`, `comp`, `rec`, `int` or `att`, because every one of
// those is itself a dictionary word. Those are exactly the abbreviations the
// standard prohibits, so the oracle is blind in precisely the direction that
// matters. The dictionary is therefore a BOOTSTRAP and not the rule: it
// classified 934 of this schema's 1,137 distinct tokens automatically, 19 of
// which were culled by hand as dictionary words that are shorthand here (see
// `culled_dictionary_words` at the foot of this file, kept as a record of the
// blind spot rather than as live input).
//
// Why not a deny-list of known-bad abbreviations. That is the enumeration trap
// this program has rejected repeatedly and that the bare-name rule was inverted
// to escape: a list of names someone already thought of reports the debt it can
// name, never the debt. A positive vocabulary inverts the default to FLAG, so
// shorthand introduced by a future migration is caught with no edit here.
//
// The cost of that inversion, accepted deliberately: a genuinely new English
// word costs one reviewed line in this file. That is the ratchet property, not
// a defect of it.
//
// Membership is judged per TOKEN, not per column. Adding a token here asserts
// that it is a word this schema may spell a concept with anywhere -- so weigh
// it against every column that could carry it, not against the one you are
// looking at.

