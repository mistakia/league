-- Pre-conditions.
DO $$
DECLARE
  baseline record;
  index_rows integer;
  unresolved integer;
  team_not_in_game integer;
  existing_pid_disagrees integer;
  colliding_groups integer;
BEGIN
  SELECT * INTO baseline FROM caesars_team_total_baseline;

  IF baseline.caesars_team_total_selections <> 3264 THEN
    RAISE EXCEPTION
      'expected 3264 CAESARS GAME_TEAM_TOTAL selections, found %; the population moved and the counts in this file are about a different one, rolling back',
      baseline.caesars_team_total_selections;
  END IF;

  SELECT count(*) INTO index_rows FROM caesars_team_total_attribution;
  IF index_rows <> 1716 THEN
    RAISE EXCEPTION
      'expected 1716 CAESARS GAME_TEAM_TOTAL index rows, found %; rolling back', index_rows;
  END IF;

  -- Exactly the eight Pro Bowl markets -- two templates, two tokens, two
  -- time_types -- whose token is AFC or NFC and which are deliberately absent
  -- from the map above. They carry one selection each.
  SELECT count(*) INTO unresolved
    FROM caesars_team_total_attribution WHERE nfl_team IS NULL;
  IF unresolved <> 8 THEN
    RAISE EXCEPTION
      'expected exactly 8 index rows with no resolvable team (the Pro Bowl AFC/NFC markets), found %; a market name shape has drifted and the derivation below would be attributing on a guess, rolling back',
      unresolved;
  END IF;

  -- THE CHECK THAT MAKES THE DERIVATION HONEST rather than a parse that cannot
  -- report failure. Every team read off a market name must be one of the two
  -- teams the game actually holds. Validated to go red: repointing one token at
  -- another team raises this from 0 to 342.
  SELECT count(*) INTO team_not_in_game
    FROM caesars_team_total_attribution AS a
    JOIN public.nfl_games AS g ON g.esbid = a.esbid
   WHERE a.nfl_team IS NOT NULL
     AND a.nfl_team NOT IN (g.home_nfl_team, g.away_nfl_team);
  IF team_not_in_game <> 0 THEN
    RAISE EXCEPTION
      '% markets resolved to a team the game does not hold; rolling back', team_not_in_game;
  END IF;

  -- Eight selections on one 2026 preseason game already carry a pid, written by
  -- the importer's player lookup resolving the full team name to a DST pid.
  -- That path covers 24 of 128 team-grain selections on a live payload, so it
  -- is not the fix -- but where it did fire it is an INDEPENDENT derivation of
  -- the same answer, and it must agree.
  SELECT count(*) INTO existing_pid_disagrees
    FROM caesars_team_total_attribution AS a
    JOIN public.prop_market_selections_index AS s
      ON s.source_id = a.source_id
     AND s.source_market_id = a.source_market_id
     AND s.time_type = a.time_type
   WHERE s.selection_pid IS NOT NULL
     AND a.nfl_team IS NOT NULL
     AND s.selection_pid <> a.nfl_team;
  IF existing_pid_disagrees <> 0 THEN
    RAISE EXCEPTION
      '% already-attributed selections disagree with the derived team; rolling back',
      existing_pid_disagrees;
  END IF;

  -- The defect, measured rather than asserted from the plan. This is the number
  -- the post-condition has to move.
  SELECT count(*) INTO colliding_groups FROM (
    SELECT 1
      FROM caesars_team_total_attribution AS a
      JOIN public.prop_market_selections_index AS s
        ON s.source_id = a.source_id
       AND s.source_market_id = a.source_market_id
       AND s.time_type = a.time_type
     WHERE a.esbid IS NOT NULL
     GROUP BY a.esbid, a.time_type, s.selection_name
    HAVING count(*) > 1
  ) AS g;
  IF colliding_groups <> 1620 THEN
    RAISE EXCEPTION
      'expected 1620 colliding (esbid, time_type, selection_name) groups before the repair, found %; rolling back',
      colliding_groups;
  END IF;

  RAISE NOTICE 'baseline: % selections, % with a null pid, % colliding groups',
    baseline.caesars_team_total_selections, baseline.null_pid, colliding_groups;
END $$;

DO $$
DECLARE
  updated integer;
BEGIN
  UPDATE public.prop_market_selections_index AS s
     SET selection_pid = a.nfl_team
    FROM caesars_team_total_attribution AS a
   WHERE s.source_id = a.source_id
     AND s.source_market_id = a.source_market_id
     AND s.time_type = a.time_type
     AND s.selection_pid IS NULL
     AND a.nfl_team IS NOT NULL;

  GET DIAGNOSTICS updated = ROW_COUNT;

  -- Exactly, not at least.
  IF updated <> 3248 THEN
    RAISE EXCEPTION
      'expected to attribute exactly 3248 selections, attributed %; rolling back', updated;
  END IF;

  RAISE NOTICE 'attributed % CAESARS GAME_TEAM_TOTAL selections', updated;
END $$;

-- Post-conditions, inside the same transaction.
DO $$
DECLARE
  baseline record;
  still_null integer;
  wrong_team integer;
  colliding_groups integer;
  residual_on_duplicate_events integer;
  null_pid_all_sources integer;
  settled_markets integer;
BEGIN
  SELECT * INTO baseline FROM caesars_team_total_baseline;

  -- Only the eight Pro Bowl selections may remain unattributed.
  SELECT count(*) INTO still_null
    FROM caesars_team_total_attribution AS a
    JOIN public.prop_market_selections_index AS s
      ON s.source_id = a.source_id
     AND s.source_market_id = a.source_market_id
     AND s.time_type = a.time_type
   WHERE s.selection_pid IS NULL;
  IF still_null <> 8 THEN
    RAISE EXCEPTION
      'expected exactly 8 selections left unattributed (the Pro Bowl AFC/NFC markets), found %; rolling back',
      still_null;
  END IF;

  SELECT count(*) INTO wrong_team
    FROM caesars_team_total_attribution AS a
    JOIN public.prop_market_selections_index AS s
      ON s.source_id = a.source_id
     AND s.source_market_id = a.source_market_id
     AND s.time_type = a.time_type
    JOIN public.nfl_games AS g ON g.esbid = a.esbid
   WHERE s.selection_pid IS NOT NULL
     AND s.selection_pid NOT IN (g.home_nfl_team, g.away_nfl_team);
  IF wrong_team <> 0 THEN
    RAISE EXCEPTION
      '% attributed selections name a team their game does not hold; rolling back', wrong_team;
  END IF;

  -- The collapse is gone: keying on selection_pid as well takes 1,620 groups
  -- to 16.
  SELECT count(*) INTO colliding_groups FROM (
    SELECT 1
      FROM caesars_team_total_attribution AS a
      JOIN public.prop_market_selections_index AS s
        ON s.source_id = a.source_id
       AND s.source_market_id = a.source_market_id
       AND s.time_type = a.time_type
     WHERE a.esbid IS NOT NULL
     GROUP BY a.esbid, a.time_type, s.selection_pid, s.selection_name
    HAVING count(*) > 1
  ) AS g;
  IF colliding_groups <> 16 THEN
    RAISE EXCEPTION
      'expected 16 residual colliding groups, found %; rolling back', colliding_groups;
  END IF;

  -- And the 16 are the OTHER defect, not this one: every remaining group sits
  -- on an esbid Caesars listed under more than one event id. Asserting the
  -- residual's cause, not just its size.
  SELECT count(*) INTO residual_on_duplicate_events FROM (
    SELECT a.esbid
      FROM caesars_team_total_attribution AS a
      JOIN public.prop_market_selections_index AS s
        ON s.source_id = a.source_id
       AND s.source_market_id = a.source_market_id
       AND s.time_type = a.time_type
     WHERE a.esbid IS NOT NULL
     GROUP BY a.esbid, a.time_type, s.selection_pid, s.selection_name
    HAVING count(*) > 1
       AND count(DISTINCT a.source_event_id) < 2
  ) AS g;
  IF residual_on_duplicate_events <> 0 THEN
    RAISE EXCEPTION
      '% residual colliding groups are NOT explained by a duplicate Caesars event listing; rolling back',
      residual_on_duplicate_events;
  END IF;

  -- No other source moved. Compared against the baseline rather than a literal,
  -- because a concurrent importer legitimately moves that number.
  SELECT count(*) FILTER (WHERE s.selection_pid IS NULL)
    INTO null_pid_all_sources
    FROM public.prop_market_selections_index AS s
    JOIN public.prop_markets_index AS i
      ON i.source_id = s.source_id
     AND i.source_market_id = s.source_market_id
     AND i.time_type = s.time_type;
  IF baseline.null_pid_all_sources - null_pid_all_sources <> 3248 THEN
    RAISE EXCEPTION
      'the all-source null-pid count fell by % rather than 3248, so this file touched rows outside its scope; rolling back',
      baseline.null_pid_all_sources - null_pid_all_sources;
  END IF;

  -- Attribution makes a market readable, not graded. GAME_TEAM_TOTAL resolves
  -- to UNSUPPORTED, and nothing here settles anything.
  SELECT count(*) FILTER (WHERE is_market_settled) INTO settled_markets
    FROM public.prop_markets_index;
  IF settled_markets <> baseline.settled_markets THEN
    RAISE EXCEPTION
      'the settled-market count moved (% vs %); rolling back',
      settled_markets, baseline.settled_markets;
  END IF;

  RAISE NOTICE 'CAESARS GAME_TEAM_TOTAL: % unattributed left, % residual colliding groups',
    still_null, colliding_groups;
END $$;
