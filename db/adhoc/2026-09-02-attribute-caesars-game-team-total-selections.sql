-- STATUS: APPLIED 2026-09-02 against league_production
--
-- Attribute the 3,248 CAESARS GAME_TEAM_TOTAL selections whose team was never
-- recorded, by deriving it from the team prefix on the market name.
--
-- THE DEFECT, which is live in production today. Caesars publishes a team total
-- as one market per team in the same game, from one template, and the
-- selections are a bare over/under:
--
--   Miami Dolphins at New York Jets - MIA Total Points  over 20.5 / under 20.5
--   Miami Dolphins at New York Jets - NYJ Total Points  over 19.5 / under 19.5
--
-- The only thing that says whose line it is, is the team prefix on the market
-- name. With selection_pid null the two markets are one key for anything
-- joining on (esbid, market_type, selection_name) -- which the data-view
-- betting columns and the historical hit-rate calculation both do. Two
-- different lines land in one cell and the observed_at dedup in
-- libs-server/market-row-dedup.mjs picks arbitrarily. Measured before this
-- file: 1,620 such groups, 1,544 of them holding conflicting metric lines.
--
-- Settlement never catches it, because GAME_TEAM_TOTAL resolves to UNSUPPORTED
-- in libs-server/prop-market-settlement/market-type-mappings.mjs. The failure
-- surfaces as a plausible wrong number rather than an error, which is why it
-- sat unnoticed since 2023-11-09.
--
-- THE FORWARD HALF SHIPS WITH THIS. private/scripts/import-caesars-odds-v4.mjs
-- now derives selection_pid from the market-name team prefix for every
-- TEAM-grain market type, so a market Caesars publishes again arrives
-- attributed and this repair does not decay. Exercised on a real payload rather
-- than read: a --dry run on base-storage over the 2026 week-1 events populated
-- 128 of 128 team-grain selections against 24 of 128 on the same payload with
-- the branch disabled.
--
-- WHY THE TEAM MAP IS MATERIALIZED HERE rather than parsed in SQL. The mapping
-- from a Caesars team token to the canonical abbreviation is fixTeam's, and
-- reproducing it in SQL would be a second implementation that can drift. The 64
-- pairs below were GENERATED by calling libs-shared/fix-team.mjs on each of the
-- 64 distinct team tokens actually stored, never hand-typed. Three of them are
-- not the canonical form -- WSC for Washington, LVR for Las Vegas, NOR for New
-- Orleans -- and WSC is an alias fixTeam gained in the same change as this file.
--
-- Caesars writes the token in two forms across eras: the 2-3 letter
-- abbreviation on the 2023-2025 'Total Home Points' and 'Total Away Points'
-- templates, and the full team name on 'Team Total Points', which is the live
-- one. Both forms are in the map.
--
-- AFC AND NFC ARE DELIBERATELY LEFT UNATTRIBUTED. Eight Pro Bowl markets, one
-- selection each. fixTeam resolves both tokens, but neither is an NFL team and
-- neither is a valid pid, and all four markets carry a null esbid, so they are
-- invisible to every consumer already. Attributing them would invent a pid that
-- joins to nothing.
--
-- WHAT THIS FILE DOES NOT CLAIM TO FIX. Sixteen selection rows still share a
-- key after the repair, and they are a different defect: Caesars listed two
-- rescheduled games -- esbid 2025010511 and 2025011300 -- under two separate
-- event ids each, so the same team has two markets in one game. The observed_at
-- dedup resolves those correctly by taking the later listing. The
-- post-condition asserts the residual is exactly those, rather than asserting a
-- zero this file cannot honestly reach.
--
-- THIS WRITE IS NOT DURABLE AGAINST A RE-OBSERVATION on its own.
-- insert-prop-markets.mjs upserts prop_market_selections_index with a bare
-- .merge(), so an incoming import overwrites selection_pid unconditionally. It
-- is durable for the right reason instead: the importer now derives the same
-- value. The two extinct templates are a belt as well, last observed 2025-10-06.

CREATE TEMP TABLE caesars_team_total_baseline ON COMMIT DROP AS
SELECT
  count(*) FILTER (WHERE i.source_id = 'CAESARS' AND i.market_type = 'GAME_TEAM_TOTAL')
    AS caesars_team_total_selections,
  count(*) FILTER (WHERE i.source_id = 'CAESARS' AND i.market_type = 'GAME_TEAM_TOTAL'
                     AND s.selection_pid IS NULL) AS null_pid,
  count(*) FILTER (WHERE s.selection_pid IS NULL) AS null_pid_all_sources,
  (SELECT count(*) FILTER (WHERE is_market_settled) FROM public.prop_markets_index)
    AS settled_markets
FROM public.prop_market_selections_index AS s
JOIN public.prop_markets_index AS i
  ON i.source_id = s.source_id
 AND i.source_market_id = s.source_market_id
 AND i.time_type = s.time_type;

